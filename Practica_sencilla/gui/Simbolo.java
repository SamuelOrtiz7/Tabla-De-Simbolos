package Practica_sencilla.gui;

public class Simbolo {

    final String nombre;
    final String tipo;
    final String categoria;
    final int nivel;

    public Simbolo(String nombre, String tipo, String categoria, int nivel) {
        this.nombre = nombre;
        this.tipo = tipo;
        this.categoria = categoria;
        this.nivel = nivel;
    }
}
